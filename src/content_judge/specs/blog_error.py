"""技术报错文的评分标准。

阈值来自今天博客产线的实测，不是拍脑袋：
· 字数下限 800 而非 1200 —— 1200 是从**允许编造的旧 prompt** 继承来的数字，
  那时模型可以自由发挥所以凑得满。加上事实边界之后，一个 `/save` 报错能确证的
  信息就那么多，硬要 1200 只能注水，而注水又撞事实边界 —— 两条要求本身矛盾。
  实测最好的一篇：中文 1032 字、总长 2561、8 个代码块、Reviewer 100 分。
· 代码块 ≥1 —— 读者搜到这一页多半是来抄那一行的。
"""
from ..judge import Spec

BLOG_ERROR = Spec(
    name="blog_error",
    length_floor=800, length_target=1500, length_full=15.0,
    code_blocks_need=1, code_blocks_full=10.0,
    symbols_full=15.0,
    subjective={
        "立场": 20.0,      # 有没有明确站队，还是中立罗列
        "边界": 15.0,      # 有没有说清哪条没验证
        "推理": 15.0,      # 报错串是嵌在推理里还是堆成参考资料
        "可读": 10.0,
    },
    subjective_brief=(
        "这是一篇技术转述文：作者基于公开 issue 与检索资料写作，**没有亲身复现过**。"
        "「没有个人操作经历」是诚实，不是扣分项；谎称「我复现了」要重罚。"
        "看的是判断力：敢不敢站队、有没有说清没验证的边界、报错串是否嵌在推理里。"),
)
