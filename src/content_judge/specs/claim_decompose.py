# -*- coding: utf-8 -*-
"""Claim Decomposer —— 选题 → required claims（带类型与检索键）。

**为什么要拆**：一个选题不能只用一句话回答。观众问一个问题时脑子里有好几层疑问，
只答其中一层，他会觉得「说了但没说清」。而**证据要按层配齐**才叫回答完整 ——
不拆的话，8 条资料全在讲同一层，成品看着有内容、其实只答了一小半。

🔴 **按受众的疑问拆，不按素材的形态拆**（2026-09-06 老板定，第三次重申）：
原来的类型表里有个 `experimental`（实验/回测结论），要求 result + method + control
—— **除了回测，没有任何素材能填满它**。于是拆层 LLM 照着这个类型，把
「连板澄清后怎么走」拆成「N 日走势」「胜率多大」，新闻类事实一层都答不上，
`covers` 恒空 ⇒ 一条可用素材都没有 ⇒ 当天三条选题全灭、缺片。

同日上午刚把「必须有回测统计」从写稿层的 REJECT 条件里删掉，
而它**从拆层就写死了** —— 位置换了，卡人的效果一模一样。
⇒ 回测只是**素材之一**：它能填 `factual` 的直接证据、能填 `causal` 的机制说明，
但**没有任何一层是非它不可的**。

🔴 **两个不能省的输出**：

1. **`type` 决定这个 claim 需要什么证据结构** —— 见 `EVIDENCE_BY_TYPE`。
   ⚠️ **不许一刀切要求所有 claim 都有反向证据**：
   「沪深300 创立至今收益多少」是事实型，强行找反方就是为形式完整添垃圾
   （同 `always.md`「闸误杀的代价是回落」）。

2. **检索键 `asset` / `condition` / `action`** —— 拆完直接就能喂给
   `factstore.recall()`。少了它们，下游还要再解析一次自然语言，
   而那一步会引入第二套判据、迟早与这里分叉。
"""
from __future__ import annotations

# claim 类型 → 这个 claim 需要哪几类证据。
# 🔴 **这是唯一真相**，prompt 里的说明从它生成，禁止手抄（`always.md` 2026-08-24）。
# 🔴 **每一类的证据要求都必须是「多种素材都填得上」的**：新闻、公告、财报、
#    回测、研报都算数。要求只有某一类素材能满足，等于把那类素材变成必要条件。
EVIDENCE_BY_TYPE: dict[str, tuple[str, ...]] = {
    # 有争议的判断题 —— 只给支持面必然偏，正反都要
    "controversial": ("support", "counter"),
    # 无争议的事实查询 —— 一条高质量直接证据就够，**不需要反方**
    "factual": ("direct",),
    # 因果断言 —— 要能说清为什么会这样
    "causal": ("mechanism",),
}

TYPE_DESC = {
    "controversial": "有争议的判断题（大家吵得起来，正反都有人信）",
    "factual": "无争议的事实查询（查一下就有确定答案）",
    "causal": "因果断言（A 导致了 B）",
}

EVIDENCE_DESC = {
    "support": "支持该判断的证据",
    "counter": "反例或边界条件（什么情况下不成立）",
    "direct": "直接回答的高质量证据",
    "mechanism": "机制解释（为什么会这样）",
}

ROLE = """你负责将短视频选题拆解为 3~4 个面向短视频受众的独立子问题（Claim）。

面向大众受众的 20~30 秒竖屏短视频。拆解的子问题必须分别覆盖事实真相、认知反差与避坑逻辑。"""

RULES = """## 拆解维度

按以下 4 层受众疑问递进拆解：
1. 核心现象：发生了什么具体市场异动或案例事件，时间与核心标的表现。
2. 认知反差：受众普遍以为的预期，与实际走势或被套结果的反差事实。
3. 背后机制：导致该反差的深层原因、资金博弈逻辑或商业运作机理。
4. 风险边界：该逻辑在什么情况下失效、存在哪些例外或下行代价。

## 红线与规则

1. 严禁拆解为仅全市场回测或复杂统计才能回答的学术命题。每一个子问题都必须是公开资讯、新闻报道、上市公司公告或财报能够回答的。
2. 拆出 3~4 个子问题，彼此互斥，合起来完整回答原选题。
3. 标注证据类型与检索意图：
   - type：factual（事实查证）/ controversial（争议反差，需正反两面证据）/ causal（因果归因机制）
   - asset：核心涉及的标的或实体名称，无则留空字符串
   - condition：前提条件或特定场景，无则留空字符串"""

OUTPUT_JSON = """## 输出格式

必须严格输出合法 JSON，包裹在 ```json 与 ``` 之间：
{
  "claims": [
    {
      "id": "C1",
      "question": "具体待验证的子问题",
      "type": "factual",
      "asset": "实体名称",
      "condition": "条件"
    }
  ]
}

`type` 只能是 factual / controversial / causal。
不要输出任何解释、前言或 Markdown 正文。"""


def render_topic(topic: str, gate: str = "", why: str = "") -> str:
    lines = [f"【选题】{topic}"]
    if gate:
        lines.append(f"【这条内容的角度】{gate}")
    if why:
        lines.append(f"【为什么值得做】{why}")
    return "\n".join(lines)


SYSTEM_BLOCKS = (ROLE, RULES, OUTPUT_JSON)
