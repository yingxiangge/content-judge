# -*- coding: utf-8 -*-
"""内容潜力打分 —— 判「这个题/这条事实做成内容有没有传播结构」。

🔴 **与本包其余 spec 的根本区别**：那些评的是**成品**（口播写得好不好），
这个评的是**成品之前的原料**（选题值不值得做、事实该用哪几条）。

**定位：淘汰器，不是预测器。**（2026-09-01 设计定稿）

  「系统应该做到的不是预测爆款，而是把明显缺乏传播条件的题先淘汰。」

这一条决定了下面所有设计：**阈值宽松 · 不追求精确分 · 不需要校准**。
一旦当成预测器用，就会掉回「攒播放数据回归权重」那条路 —— 而 300 播放/条
的体量，完播率的噪声比任何效应都大，那个回归**在数学上就跑不出显著结果**。

---

## 两层结构：硬门在前，打分只管排序

**第一层 · 转发理由测试（二值，不可加权）**

一个选题必须至少满足一条，否则淘汰：

  · `A` 警告   —— 「你家里炒股的人可能正在这么亏钱」
  · `B` 打脸   —— 「大家都信的这件事，数据不支持」
  · `C` 反常识 —— 「看起来最安全的操作，反而少赚了这么多」

🔴 **淘汰只由硬门决定，不由分数决定**：82.6 分与 79.3 分的差别是噪声，
而「有没有打脸点」是事实。让分数承担淘汰职责 = 拿噪声做决策。

**第二层 · 三维打分（只在过闸的候选之间排序）**

理论依据：Berger & Milkman (2012, JMR) 对《纽约时报》三个月全部文章的分析 +
实验验证 —— **高唤醒情绪（敬畏/惊讶/愤怒/焦虑）显著提升传播**，
且「有用 / 有趣 / 令人惊讶」本身与传播正相关。

⚠️ **为什么是三维不是六维**（Relevance/Curiosity/Conflict/Emotional/Utility/
Specificity）：那六个不正交。一条「越跌越买真的安全吗」，Conflict 高的同时
Curiosity 必然高、Emotional 必然高 —— 模型会打出高度相关的三个分，
加权等于把同一个信号数了三遍，权重随之失去意义。⇒ 合并成三个正交维度：

| 维度 | 吃掉原来的 | 问的是 |
|---|---|---|
| Relevance | Relevance | 关我什么事？我的钱会怎样 |
| Tension   | Conflict + Curiosity + Emotional | 跟我想的不一样吗？信息缺口在哪 |
| Utility   | Utility + Specificity | 看完我能拿走什么 |

⚠️ **权重首版是拍的**（35/40/25），照 `journal 2026-08-30` 那条规矩如实标注。
但**它不重要**：分数只排序不淘汰，而排序对权重不敏感。**不许凭手感调**。
"""
from __future__ import annotations

# 转发理由（硬门）。🔴 **二值判定，不参与加权。**
GATES = {
    "A": "警告 —— 观众或其家人可能正在这么亏钱",
    "B": "打脸 —— 大家普遍相信的事，数据不支持",
    "C": "反常识 —— 看起来最安全/最合理的做法，结果相反",
}

# 三维权重（首版拍的·只影响排序不影响淘汰）
WEIGHTS = {"relevance": 35, "tension": 40, "utility": 25}

ROLE = """你是短视频内容策划，负责判断一个选题**做成 20~30 秒竖屏视频后，
观众会不会看完、会不会转发**。

面向人群：A 股散户，刷视频号，注意力以秒计。

🔴 你判的**不是**这个话题重不重要、专不专业、数据准不准 ——
那些由别的环节负责。你只判**传播结构**：观众有没有理由停下来、看完、转给别人。"""

GATE_SPEC = """## 第一层：转发理由测试（先判这个）

一个选题必须至少满足下面一条，否则**直接淘汰**：

- **A 警告**：观众或其家人可能正在这么亏钱。
  例：「越跌越补，可能把现金流耗光」
- **B 打脸**：大家普遍相信的事，数据不支持。
  例：「都说定投稳赚，19 年数据里有一半人没赚到」
- **C 反常识**：看起来最安全/最合理的做法，结果反而更差。
  例：「割在恐慌里的人，比扛着的少赚了这么多」

三条都不满足就是 `gate: null` —— 这类题**再准确也没人看完**，因为观众想不出
任何理由停下来。典型的三不沾：「某某指数今日收涨」「某行业迎来政策利好」。

⚠️ **不要为了让它过闸而脑补**。素材里没有打脸点，就是没有。"""

DIM_SPEC = """## 第二层：三维打分（0-10 分，只用来排序）

- **Relevance 关我什么事**（0-10）
  观众看到标题的 3 秒内，能不能想到「这跟我的钱有关」。
  · 9-10：直接指向观众正在经历的处境（套牢了 / 亏了 10 个点 / 想抄底）
  · 5-6：行业或市场层面，需要转一道弯才关联到自己
  · 0-2：宏观、海外、机构视角，散户想不到关系

- **Tension 跟我想的不一样**（0-10）
  信息缺口 + 认知冲突 + 情绪唤起，合成一个维度。
  · 9-10：明确的「多数人以为 A，实际是 B」，且 B 有反差
  · 5-6：有悬念但结论平淡（「有影响，但影响有限」）
  · 0-2：结论符合直觉，看不看都一样

- **Utility 我能拿走什么**（0-10）
  看完得到一个**具体**的东西：一个数、一条边界、一个判断依据。
  🔴 **不是「我该怎么操作」** —— 那是荐股，是红线。是「我知道了什么」。
  · 9-10：一个能记住并复述给别人的具体结论
  · 5-6：加深了理解，但说不出具体是什么
  · 0-2：看完只剩情绪，没有信息"""

OUTPUT_JSON = """## 输出格式

只输出合法 JSON，包裹在 ```json 与 ``` 之间。**逐条对应输入的编号**：

{
  "items": [
    {"id": 1, "gate": "B", "relevance": 8, "tension": 9, "utility": 6,
     "why": "一句话说明过闸理由和最强的那一维"},
    {"id": 2, "gate": null, "relevance": 3, "tension": 2, "utility": 4,
     "why": "三条转发理由都不沾，宏观题"}
  ]
}

⚠️ `gate` 只能是 "A"/"B"/"C"/null。三维分是 0-10 的整数。
⚠️ **必须逐条给出**，输入几条就输出几条，不许省略、不许合并。
不要输出任何解释、前言或 Markdown 正文。"""


def render_batch(items: list[dict]) -> str:
    """待评条目 → user 消息。**批量评而不是逐条**。

    🔴 逐条评有两个问题：调用次数 ×N；且模型看不到横向对比，
    打出来的分在条目之间不可比 —— 而我们要的恰恰是**排序**。
    """
    lines = ["【待评选题】", ""]
    for n, it in enumerate(items, 1):
        lines.append(f"{n}. {it.get('title', '')}")
        if it.get("why"):
            lines.append(f"   （为什么成为话题：{it['why']}）")
        body = (it.get("body") or "").strip()
        if body:
            lines.append(f"   摘要：{body[:180]}")
    return "\n".join(lines)


SYSTEM_BLOCKS = (ROLE, GATE_SPEC, DIM_SPEC, OUTPUT_JSON)
