"""内容潜力打分 —— 判「这个题/这条事实做成内容有没有传播结构」。

🔴 **与本包其余 spec 的根本区别**：那些评的是**成品**（口播写得好不好），
这个评的是**成品之前的原料**（选题值不值得做、事实该用哪几条）。

**定位：淘汰器，不是预测器。**（2026-09-01 设计定稿）

  「系统应该做到的不是预测爆款，而是把明显缺乏传播条件的题先淘汰。」

这一条决定了下面所有设计：**阈值宽松 · 不追求精确分 · 不需要校准**。
一旦当成预测器用，就会掉回「攒播放数据回归权重」那条路 —— 而 300 播放/条
的体量，完播率的噪声比任何效应都大，那个回归**在数学上就跑不出显著结果**。

---

## 两层结构：硬门在前，打分只管排序

**第一层 · 三道硬门（全过才入池）**

  · `G1` 账户动作     —— 问题里有观众的动作或持仓关系
  · `G2` 二级市场标的 —— 股票/指数/基金/转债/期权，宏观与国际局势本身不算
  · `G4` 内容张力     —— 存在明确的「预期 vs 结果」，且必须写出 expected / test

🔴 **2026-09-06 改**：原设计是「A 警告 / B 打脸 / C 反常识 三选一」，实测
34 条过 15 条（44%）—— 对一个淘汰器明显偏松。病根是**模型能自我欺骗**：
任何题都能说成「提醒投资者注意风险」，于是 A 恒真。
⇒ 改成必须**写出**「观众原来相信什么 / 历史可能推翻它什么」两句话，
写不出就是没张力。**用「必须产出具体内容」防自欺，比加词表管用。**
原 A/B/C 降级为 `hook_type` 标注（warning / debunk / counterintuitive），
只描述张力的类型，不再承担淘汰职责。

⚠️ **G3（可不可验证）不在本 spec** —— 那是 `topic_gate` 用代码查
testable 四要素的事。结构检查交给模型只会引入抖动，还多花一次调用。

🔴 **淘汰只由硬门决定，不由分数决定**：82.6 分与 79.3 分的差别是噪声，
而「有没有张力」是事实。让分数承担淘汰职责 ＝ 拿噪声做决策。

**第二层 · 三维打分（只在过闸的候选之间排序）**

理论依据：Berger & Milkman (2012, JMR) 对《纽约时报》三个月全部文章的分析 +
实验验证 —— **高唤醒情绪（敬畏/惊讶/愤怒/焦虑）显著提升传播**，
且「有用 / 有趣 / 令人惊讶」本身与传播正相关。

⚠️ **为什么是三维不是六维**（Relevance/Curiosity/Conflict/Emotional/Utility/
Specificity）：那六个不正交。一条「越跌越买真的安全吗」，Conflict 高的同时
Curiosity 必然高、Emotional 必然高 —— 模型会打出高度相关的三个分，
加权等于把同一个信号数了三遍，权重随之失去意义。⇒ 合并成三个正交维度：

| 维度 | 吃掉原来的 | 问的是 |
|---|---|---|
| Relevance | Relevance | 关我什么事？我的钱会怎样 |
| Tension   | Conflict + Curiosity + Emotional | 跟我想的不一样吗？信息缺口在哪 |
| Utility   | Utility + Specificity | 看完我能拿走什么 |

⚠️ **权重首版是拍的**（35/40/25），照 `journal 2026-08-30` 那条规矩如实标注。
但**它不重要**：分数只排序不淘汰，而排序对权重不敏感。**不许凭手感调**。
"""
from __future__ import annotations

import json

# 张力类型标注。🔴 **只描述类型，不承担淘汰职责**（淘汰看三道硬门是否全过）。
HOOK_TYPES = {
    "warning":          "警告 —— 观众或其家人可能正在这么亏钱",
    "debunk":           "打脸 —— 大家普遍相信的事，数据不支持",
    "counterintuitive": "反常识 —— 看起来最安全/最合理的做法，结果相反",
}
# 三道硬门的字段名，与 spec 输出的 gate 对象一一对应。**全 True 才算过。**
GATE_KEYS = ("account_action", "secondary_market", "cognitive_contrast")

# 四维权重（兼容保留）
WEIGHTS = {"audience": 30, "relevance": 25, "tension": 25, "utility": 20}

ROLE = """# 角色
你是短视频选题的准入门禁裁判，面向 A 股普通散户投资者。
你只评估候选选题的传播结构，负责在入库前淘汰不合格选题。

# 核心任务
审查输入的 JSON 数组，每项为 {"id": 数字, "topic": 选题文本}。id 照抄输入，不得重排。
三道硬门一票否决：三项全满足才放行；任一不满足直接淘汰，停止后续判断。
每条选题独立按三门重判，禁止因与任何历史选题表面相似而直接给结论。"""

GATE_SPEC = """# 三道硬门
G1 账户动作
散户账户里的钱只有两种存在状态：场外（现金）与 场内（持仓）。
选题必须能引导观众做出明确的资金决策（状态转换或状态维持）：
- 现金 → 持仓（买入、加仓、追涨、抄底）
- 持仓 → 现金（卖出、减仓、清仓、割肉、止盈、止损）
- 维持持仓（持有：承受机会成本的不动决策）
- 维持现金（空仓观望：不进场）
- 持仓 A → 持仓 B（调仓）

🔴 检验标准只有一句话：看完这个选题，观众能不能明确「我该拿我的钱怎么办」。
- 能明确指导资金决策的（包含行情的二元博弈设问，如“诱多还是反转”→诱多则卖出/空仓，反转则持有/买入），判定通过；
- 无法指导具体资金去向、仅为泛行业背景介绍、客观事实通报、无决策主体的，一律淘汰。

G2 二级市场本土标的
核心博弈标的必须直接对应散户可下单的本土连续交易品种（默认 A 股）。
淘汰：事实主体是海外远端产业或泛宏观指标，硬蹭一个本土行业概念的选题。

G3 认知反差与交易博弈
选题必须具备明确的认知反差或预期的利益博弈，仅限以下两类：
1. 事实对撞型：原文自带相反客观数据或事实对撞；
2. 交易博弈型：重大事件引发大众普遍认为必然上涨的直觉共识，但标题直击交易疑虑。
🔴 假大空拦截铁律：交易博弈型的标题疑虑，必须能明确回扣到 G1 的具体资金决策（买/卖/持/调/空）。凡无法对应具体账户买卖持仓决策的空泛设问，一律视为无认知反差淘汰。
淘汰：常规远期规划、无博弈的单向通报、平铺直叙的新闻公文。

# 防偷懒
通过项的 why 必须逐门引用原文片段：
- G1「原文」→ 明确的资金状态决策（如：持仓→现金/卖出）；
- G2「原文」→ 对应交易品种；
- G3 事实对撞型写：直觉「原文」vs 事实「原文」；交易博弈型写：事实「原文」vs 疑虑「原文」，且必须回扣 G1 资金决策。
找不到原文依据的门即判不满足，不得用常识或推测补足。
淘汰项的 why 写清死在哪一门，并引用导致淘汰的原文片段与缺陷。"""

OUTPUT_JSON = """# 输出格式
严格输出合法纯 JSON，不要用 markdown 代码块包裹，禁止任何额外自然语言：
{"items": [{"id": 1, "gate": {"account_action": true, "secondary_market": true, "cognitive_contrast": true}, "expected": "大众直觉", "test": "事实「」vs 疑虑「」", "why": "G1「」→；G2「」→；G3「」vs「」"}, {"id": 2, "gate": null, "expected": "", "test": "", "why": "G2：「原文片段」→具体缺陷"}]}"""


def render_batch(items: list[dict]) -> str:
    """待评条目 → user 消息。返回格式化的 JSON 数组字符串。"""
    payload = []
    for n, it in enumerate(items, 1):
        name = it.get("name") or it.get("title") or ""
        event = it.get("event") or it.get("why") or it.get("from") or ""
        text = f"【标题】{name}"
        if event:
            text += f" | 【事实】{event}"
        payload.append({"id": n, "topic": text.strip()})
    return json.dumps(payload, ensure_ascii=False)


SYSTEM_BLOCKS = (ROLE, GATE_SPEC, OUTPUT_JSON)

